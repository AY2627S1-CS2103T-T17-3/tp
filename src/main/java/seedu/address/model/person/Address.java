package seedu.address.model.person;

import static java.util.Objects.requireNonNull;
import static seedu.address.commons.util.AppUtil.checkArgument;

import java.util.regex.Pattern;

/**
 * Represents a Person's address in the address book.
 * Guarantees: immutable; is valid as declared in {@link #isValidAddress(String)}
 */
public class Address {

    public static final int MAX_LENGTH = 200;

    public static final String MESSAGE_CONSTRAINTS =
            "Addresses must contain at least one non-whitespace character and be at most "
            + MAX_LENGTH + " characters long.";

    /*
     * The first character of the address must not be a whitespace,
     * otherwise " " (a blank string) becomes a valid input.
     */
    public static final String VALIDATION_REGEX = "[^\\s].*";

    private static final Pattern BLANK_ADDRESS_PATTERN = Pattern.compile("\\p{IsWhite_Space}*");

    public final String value;

    /**
     * Constructs an {@code Address}.
     *
     * @param address A valid address.
     */
    public Address(String address) {
        requireNonNull(address);
        checkArgument(isValidAddress(address), MESSAGE_CONSTRAINTS);
        value = address;
    }

    /**
     * Returns true if a given string is a valid address.
     */
    public static boolean isValidAddress(String test) {
        return test.length() <= MAX_LENGTH && test.matches(VALIDATION_REGEX) && !isBlankAddress(test);
    }

    /**
     * Returns true if {@code address} is empty or contains only Unicode White_Space characters.
     */
    public static boolean isBlankAddress(String address) {
        requireNonNull(address);
        return BLANK_ADDRESS_PATTERN.matcher(address).matches();
    }

    @Override
    public String toString() {
        return value;
    }

    @Override
    public boolean equals(Object other) {
        if (other == this) {
            return true;
        }

        // instanceof handles nulls
        if (!(other instanceof Address otherAddress)) {
            return false;
        }

        return value.equals(otherAddress.value);
    }

    @Override
    public int hashCode() {
        return value.hashCode();
    }

}
